// Bundles entry.mjs into Resources/Browser/vendor/sui-sdk.js: an IIFE
// evaluated on first use by providers/sui.js, the same way tronweb.js is.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const output = join(here, '../../Resources/Browser/vendor/sui-sdk.js');

const result = await build({
    entryPoints: [join(here, 'entry.mjs')],
    bundle: true,
    format: 'iife',
    globalName: 'suiSDK',
    minify: true,
    target: 'safari18',
    legalComments: 'none',
    metafile: true,
    write: false,
});

// One license line per bundled package.
const packages = new Map();

for (const input of Object.keys(result.metafile.inputs)) {
    const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);

    if (match && !packages.has(match[1])) {
        const manifest = JSON.parse(readFileSync(join(here, 'node_modules', match[1], 'package.json'), 'utf8'));
        packages.set(match[1], `//   ${match[1]}@${manifest.version} — ${manifest.license}`);
    }
}

const sui = JSON.parse(readFileSync(join(here, 'node_modules/@mysten/sui/package.json'), 'utf8'));
const lock = createHash('sha256').update(readFileSync(join(here, 'package-lock.json'))).digest('hex');
const bundle = result.outputFiles[0].text.trim();

writeFileSync(output, `// vendor/sui-sdk.js — GENERATED by Scripts/sui-sdk (npm ci && npm run build),
// don't edit. @mysten/sui@${sui.version} \`Transaction\`, bundled with esbuild
// (package-lock.json sha256 ${lock}),
// inside a wrapper so it neither runs on page load nor touches page globals:
// providers/sui.js calls \`window.__reefrLoadSuiSDK()\` on the first
// transaction it builds. Bundled packages:
${[...packages.values()].sort().join('\n')}
(function () {
    if (window.__reefrLoadSuiSDK) {
        return;
    }

    var loaded = null;

    function load() {
        if (loaded) {
            return loaded;
        }

// ---- BEGIN bundle ----
${bundle}
// ---- END bundle ----

        loaded = suiSDK;
        return loaded;
    }

    Object.defineProperty(window, '__reefrLoadSuiSDK', {
        value: load,
        writable: false,
        configurable: false,
        enumerable: false,
    });
})();
`);
